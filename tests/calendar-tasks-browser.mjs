import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from 'playwright-core';

const base = process.env.TRACKME_URL || process.env.STUDYTRACK_URL || 'http://127.0.0.1:4174';
const output = '/tmp/studytrack-calendar-tasks';
fs.mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Kolkata', reducedMotion: 'reduce' });
page.setDefaultTimeout(10000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => { errors.push('Unexpected native dialog'); dialog.dismiss(); });
const go = async route => { await page.goto(`${base}/${route}`); await page.locator('.route-frame').waitFor(); };
const data = () => page.evaluate(() => JSON.parse(localStorage.getItem('studytrack.workspace.v1')));
const day = date => page.getByRole('button', { name: new RegExp(`^${date},`) });
const selectDay = async date => { await day(date).click(); await page.waitForFunction(date => document.querySelector('.calendar-day.selected')?.getAttribute('aria-label')?.startsWith(date), date); };
const openCreate = async () => { await page.getByRole('button', { name: 'Add task for selected day', exact: true }).click(); await page.getByRole('dialog', { name: 'New task', exact: true }).waitFor(); };
const saveCreate = async () => { await page.getByRole('button', { name: 'Create task', exact: true }).click(); await page.getByRole('dialog').waitFor({ state: 'hidden' }); };
try {
  await go('calendar');
  const today = (await page.locator('.calendar-day.today').getAttribute('aria-label')).slice(0, 10);
  const future = `${today.slice(0, 8)}26`;
  const past = `${today.slice(0, 8)}03`;
  const deadline = `${today.slice(0, 8)}28`;
  await selectDay(future);
  await openCreate();
  assert.equal(await page.getByLabel('Study plan date').inputValue(), future);
  assert.equal(await page.getByLabel('Due date', { exact: true }).inputValue(), future);
  await page.getByLabel('Task title', { exact: true }).fill('Calendar revision');
  await page.getByLabel('Description', { exact: true }).fill('Review chapters and practice questions.');
  await page.getByRole('combobox', { name: 'Category', exact: true }).click();
  await page.getByRole('combobox', { name: 'Search categories', exact: true }).fill('Physics');
  await page.getByRole('option', { name: 'Create “Physics”', exact: true }).click();
  await page.getByLabel('Estimated Pomodoros', { exact: true }).fill('3');
  await page.getByLabel('Minutes per Pomodoro', { exact: true }).fill('40');
  await page.getByLabel('Due date', { exact: true }).fill(deadline);
  await page.getByRole('combobox', { name: 'Priority', exact: true }).click();
  await page.getByRole('option', { name: 'High', exact: true }).click();
  await page.screenshot({ path: `${output}/shared-task-form-desktop.png` });
  await saveCreate();
  const created = (await data()).tasks.find(task => task.title === 'Calendar revision');
  assert.equal(created.plannedDate, future);
  assert.equal(created.dueDate, deadline);
  assert.equal(created.pomodoroMinutes, 40);
  assert.equal(created.estimatedPomodoros, 3);
  assert.equal(created.priority, 'high');
  assert.equal(created.category, 'Physics');
  assert.match(await page.locator('.calendar-sidebar').innerText(), /Calendar revision/);
  assert.match(await day(future).innerText(), /Calendar revision/);
  assert.doesNotMatch(await day(deadline).innerText(), /Calendar revision/);
  await go(`tasks?date=${future}`);
  assert.match(await page.locator('.task-kanban').innerText(), /Calendar revision/);
  await go('tasks?scope=unscheduled');
  assert.equal(await page.locator('.task-card').count(), 0);
  await go('plan');
  await page.getByLabel('Plan date', { exact: true }).fill(future);
  await page.getByRole('button', { name: 'Calendar revision', exact: true }).waitFor();
  console.log('PASS full shared task creation, Pomodoro settings, independent deadline, and Tasks/Daily Plan alignment');

  await go('calendar'); await selectDay(future);
  await page.getByRole('button', { name: 'Edit task Calendar revision', exact: true }).click();
  await page.getByRole('dialog', { name: 'Task detail', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Minutes per Pomodoro', { exact: true }).inputValue(), '40');
  await page.getByLabel('Study plan date').fill(past);
  await page.getByLabel('Minutes per Pomodoro', { exact: true }).fill('35');
  await page.getByPlaceholder('Add subtask', { exact: true }).fill('Practice five questions');
  await page.getByRole('button', { name: 'Add subtask', exact: true }).click();
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.doesNotMatch(await page.locator('.calendar-sidebar').innerText(), /Calendar revision/);
  await selectDay(past);
  assert.match(await page.locator('.calendar-sidebar').innerText(), /Calendar revision/);
  const edited = (await data()).tasks.find(task => task.id === created.id);
  assert.equal(edited.dueDate, deadline); assert.equal(edited.pomodoroMinutes, 35); assert.equal(edited.subtasks.length, 1);
  await openCreate();
  await page.getByLabel('Task title', { exact: true }).fill('Past practice');
  await saveCreate();
  assert.equal((await data()).tasks.find(task => task.title === 'Past practice').plannedDate, past);
  await page.locator('.calendar-sidebar .task-event').filter({ hasText: 'Calendar revision' }).dragTo(day(future));
  await page.waitForFunction(id => JSON.parse(localStorage.getItem('studytrack.workspace.v1')).tasks.find(task => task.id === id).plannedDate.endsWith('-26'), created.id);
  assert.equal((await data()).tasks.find(task => task.id === created.id).dueDate, deadline);
  assert.match(await page.locator('.calendar-sidebar').innerText(), /Calendar revision/);
  console.log('PASS shared editing, past day creation, subtasks, and drag scheduling preserves deadlines');

  await openCreate();
  await page.getByLabel('Task title', { exact: true }).fill('Cancelled draft');
  await page.getByRole('combobox', { name: 'Priority', exact: true }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 1);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal((await data()).tasks.length, 2);
  assert.equal(await page.getByRole('button', { name: 'Add task for selected day', exact: true }).evaluate(el => el === document.activeElement), true);
  // Old tasks with only a deadline stay discoverable and can be explicitly scheduled.
  await go('tasks?scope=unscheduled');
  await page.getByRole('button', { name: 'New Task', exact: true }).click();
  await page.getByLabel('Task title', { exact: true }).fill('Legacy deadline');
  await page.getByLabel('Due date', { exact: true }).fill(future);
  await saveCreate();
  await go('calendar'); await selectDay(future);
  assert.match(await page.locator('.calendar-sidebar').innerText(), /Deadline · unscheduled/);
  await page.getByRole('button', { name: 'Week', exact: true }).click();
  assert.equal(await page.locator('.calendar-day').count(), 7);
  assert.match(await day(future).innerText(), /Calendar revision/);
  await page.getByRole('button', { name: 'Month', exact: true }).click();
  console.log('PASS Escape handling, focus restoration, cancellation, legacy deadlines, and week view');

  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('.main-panel').evaluate(el => el.scrollWidth > el.clientWidth), false);
  await openCreate();
  assert.equal(await page.getByLabel('Study plan date').inputValue(), future);
  await page.getByLabel('Task title', { exact: true }).fill('Mobile study');
  await page.getByLabel('Minutes per Pomodoro', { exact: true }).fill('20');
  await page.getByRole('button', { name: 'Create task', exact: true }).scrollIntoViewIfNeeded();
  assert.equal(await page.getByRole('dialog').evaluate(el => el.scrollWidth > el.clientWidth), false);
  await page.screenshot({ path: `${output}/shared-task-form-mobile.png` });
  await saveCreate();
  assert.equal((await data()).tasks.find(task => task.title === 'Mobile study').plannedDate, future);
  await page.getByRole('button', { name: 'View all tasks for selected day', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Edit task Mobile study', exact: true }).click();
  await page.getByRole('dialog', { name: 'Task detail', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.deepEqual(errors, []);
  console.log('PASS mobile creation, list-to-editor handoff, modal layout, and no browser errors');
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` });
  console.error(error); process.exitCode = 1;
} finally { await browser.close(); }
